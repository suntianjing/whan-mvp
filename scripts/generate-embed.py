#!/usr/bin/env python3
"""Regenerate js/data-embed.js from data/*.json so file:// and offline work."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
OUT = ROOT / "js" / "data-embed.js"

FILES = {
    "market": "market.json",
    "newhomes": "newhomes.json",
    "secondhand": "secondhand.json",
}

OPTIONAL = {
    "history": DATA / "official" / "history_monthly.json",
    "daily": DATA / "official" / "latest_daily.json",
}


def main() -> None:
    payload = {}
    for key, name in FILES.items():
        with open(DATA / name, encoding="utf-8") as f:
            payload[key] = json.load(f)
    for key, path in OPTIONAL.items():
        if path.exists():
            try:
                payload[key] = json.loads(path.read_text(encoding="utf-8"))
            except (json.JSONDecodeError, OSError) as e:
                print(f"warn: skip {path.name}: {e}")
    body = json.dumps(payload, ensure_ascii=False, indent=2)
    OUT.write_text(
        "/* Auto-generated by scripts/generate-embed.py — do not edit by hand. */\n"
        "window.WHAN_EMBED = "
        + body
        + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT.relative_to(ROOT)} keys={list(payload)}")


if __name__ == "__main__":
    main()
